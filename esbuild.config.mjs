import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const common = {
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	minify: prod,
};

// Plugin entry: src/main.ts -> main.js
await esbuild.build({
	...common,
	entryPoints: ["src/main.ts"],
	outfile: "main.js",
	banner: { js: banner },
});

// Test entry: tests/*.test.ts -> dist-test/*.test.cjs (run with `node --test dist-test/`)
await esbuild.build({
	...common,
	entryPoints: ["tests/index.ts"],
	outfile: "dist-test/index.test.cjs",
	banner: { js: banner },
	platform: "node",
	sourcemap: false,
	// 不压缩：压缩成单行后，node --test 的错误格式化器（getErrorSourceExpression）
	// 解析该行提取断言表达时会崩（Unterminated template），反而掩盖真实断言失败
	minify: false,
});
